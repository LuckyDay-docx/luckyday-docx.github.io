export const kitchenBySlug = Object.fromEntries(kitchenSets.map((k) => [k.slug, k]));

/** Список URL кадров для карточки (кроп 4:3). */
export const cardShots = (slug: string): string[] => {
  const set = kitchenBySlug[slug];
  if (!set) return [];
  return Array.from({ length: set.shots }, (_, i) => `/images/kitchens/${slug}/${i + 1}.webp`);
};
